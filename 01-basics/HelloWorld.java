/**
 * HelloWorld.java
 *
 * The simplest Java program possible. It prints two lines to the console.
 * Use this as a template for understanding the structure of every Java file.
 */
public class HelloWorld {

    // The main method — entry point of every standalone Java program.
    // The JVM looks for this exact signature when you run the class.
    public static void main(String[] args) {

        // println prints the text and adds a new line at the end.
        System.out.println("Hello, World!");

        // You can also use print (no new line) and then println.
        System.out.print("Welcome ");
        System.out.println("to Core Java revision.");
    }
}
